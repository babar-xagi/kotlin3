use crate::manifest::{parse_string_array, strip_comment, unquote};
use std::fs;
use std::path::Path;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LockedPackage {
    pub group: String,
    pub artifact: String,
    pub version: String,
    pub sha256: String,
    pub url: String,
    pub scope: String,
    pub dependencies: Vec<String>,
}

impl LockedPackage {
    pub fn coordinate(&self) -> String {
        format!("{}:{}", self.group, self.artifact)
    }

    pub fn full_coordinate(&self) -> String {
        format!("{}:{}:{}", self.group, self.artifact, self.version)
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct K3Lockfile {
    pub version: u32,
    pub kotlin_version: String,
    pub packages: Vec<LockedPackage>,
}

impl Default for K3Lockfile {
    fn default() -> Self {
        Self {
            version: 1,
            kotlin_version: "2.4.21".to_string(),
            packages: Vec::new(),
        }
    }
}

impl K3Lockfile {
    pub fn load(path: &Path) -> Result<Self, String> {
        let content = fs::read_to_string(path)
            .map_err(|e| format!("Failed to read {}: {}", path.display(), e))?;
        Self::parse(&content)
    }

    pub fn save(&self, path: &Path) -> Result<(), String> {
        fs::write(path, self.to_toml_string())
            .map_err(|e| format!("Failed to write {}: {}", path.display(), e))
    }

    pub fn parse(input: &str) -> Result<Self, String> {
        let mut lock = Self::default();
        let mut current: Option<LockedPackage> = None;

        for raw_line in input.lines() {
            let line = strip_comment(raw_line).trim();
            if line.is_empty() {
                continue;
            }
            if line == "[[package]]" {
                if let Some(pkg) = current.take() {
                    lock.packages.push(pkg);
                }
                current = Some(LockedPackage {
                    group: String::new(),
                    artifact: String::new(),
                    version: String::new(),
                    sha256: String::new(),
                    url: String::new(),
                    scope: "compile".to_string(),
                    dependencies: Vec::new(),
                });
                continue;
            }
            let Some((raw_k, raw_v)) = line.split_once('=') else {
                continue;
            };
            let k = raw_k.trim();
            let v = raw_v.trim();
            if let Some(pkg) = current.as_mut() {
                match k {
                    "group" => pkg.group = unquote(v),
                    "artifact" => pkg.artifact = unquote(v),
                    "version" => pkg.version = unquote(v),
                    "sha256" => pkg.sha256 = unquote(v),
                    "url" => pkg.url = unquote(v),
                    "scope" => pkg.scope = unquote(v),
                    "dependencies" => pkg.dependencies = parse_string_array(v),
                    _ => {}
                }
            } else {
                match k {
                    "version" => lock.version = v.parse().unwrap_or(1),
                    "kotlin" => lock.kotlin_version = unquote(v),
                    _ => {}
                }
            }
        }
        if let Some(pkg) = current {
            lock.packages.push(pkg);
        }
        Ok(lock)
    }

    pub fn to_toml_string(&self) -> String {
        let mut out = String::new();
        out.push_str("# Auto-generated by k3 (Kotlin3 lockfile). Do not edit manually.\n");
        out.push_str(&format!("version = {}\n", self.version));
        out.push_str(&format!("kotlin = \"{}\"\n", self.kotlin_version));

        let mut sorted = self.packages.clone();
        sorted.sort_by(|a, b| a.full_coordinate().cmp(&b.full_coordinate()));

        for pkg in &sorted {
            out.push_str("\n[[package]]\n");
            out.push_str(&format!("group = \"{}\"\n", pkg.group));
            out.push_str(&format!("artifact = \"{}\"\n", pkg.artifact));
            out.push_str(&format!("version = \"{}\"\n", pkg.version));
            out.push_str(&format!("scope = \"{}\"\n", pkg.scope));
            out.push_str(&format!("sha256 = \"{}\"\n", pkg.sha256));
            out.push_str(&format!("url = \"{}\"\n", pkg.url));
            if !pkg.dependencies.is_empty() {
                let deps: Vec<String> = pkg.dependencies.iter().map(|d| format!("\"{}\"", d)).collect();
                out.push_str(&format!("dependencies = [{}]\n", deps.join(", ")));
            }
        }
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_lockfile_roundtrip() {
        let lock = K3Lockfile {
            version: 1,
            kotlin_version: "2.4.21".to_string(),
            packages: vec![LockedPackage {
                group: "org.jetbrains.kotlin".to_string(),
                artifact: "kotlin-stdlib".to_string(),
                version: "2.4.21".to_string(),
                sha256: "deadbeef".to_string(),
                url: "https://repo1.maven.org/maven2/org/jetbrains/kotlin/kotlin-stdlib/2.4.21/kotlin-stdlib-2.4.21.jar".to_string(),
                scope: "compile".to_string(),
                dependencies: vec!["org.jetbrains:annotations:13.0".to_string()],
            }],
        };

        let text = lock.to_toml_string();
        let parsed = K3Lockfile::parse(&text).unwrap();
        assert_eq!(parsed, lock);
    }
}
