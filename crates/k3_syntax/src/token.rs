use logos::Logos;

#[derive(Logos, Debug, Clone, PartialEq, Eq)]
#[logos(skip r"[ \t\r\n\f]+")]
#[logos(skip r"//[^\r\n]*")]
#[logos(skip r"/\*([^*]|\*[^/])*\*/")]
pub enum TokenKind {
    // Hard Keywords
    #[token("as")]
    As,
    #[token("as?")]
    AsSafe,
    #[token("break")]
    Break,
    #[token("class")]
    Class,
    #[token("continue")]
    Continue,
    #[token("do")]
    Do,
    #[token("else")]
    Else,
    #[token("false")]
    False,
    #[token("for")]
    For,
    #[token("fun")]
    Fun,
    #[token("if")]
    If,
    #[token("in")]
    In,
    #[token("!in")]
    NotIn,
    #[token("interface")]
    Interface,
    #[token("is")]
    Is,
    #[token("!is")]
    NotIs,
    #[token("null")]
    Null,
    #[token("object")]
    Object,
    #[token("package")]
    Package,
    #[token("return")]
    Return,
    #[token("super")]
    Super,
    #[token("this")]
    This,
    #[token("throw")]
    Throw,
    #[token("true")]
    True,
    #[token("try")]
    Try,
    #[token("typealias")]
    TypeAlias,
    #[token("val")]
    Val,
    #[token("var")]
    Var,
    #[token("when")]
    When,
    #[token("while")]
    While,

    // Soft Keywords / Modifiers
    #[token("import")]
    Import,
    #[token("by")]
    By,
    #[token("catch")]
    Catch,
    #[token("constructor")]
    Constructor,
    #[token("delegate")]
    Delegate,
    #[token("dynamic")]
    Dynamic,
    #[token("field")]
    Field,
    #[token("file")]
    File,
    #[token("finally")]
    Finally,
    #[token("get")]
    Get,
    #[token("init")]
    Init,
    #[token("param")]
    Param,
    #[token("property")]
    Property,
    #[token("receiver")]
    Receiver,
    #[token("set")]
    Set,
    #[token("setparam")]
    SetParam,
    #[token("where")]
    Where,
    #[token("actual")]
    Actual,
    #[token("abstract")]
    Abstract,
    #[token("annotation")]
    Annotation,
    #[token("companion")]
    Companion,
    #[token("const")]
    Const,
    #[token("crossinline")]
    Crossinline,
    #[token("data")]
    Data,
    #[token("enum")]
    Enum,
    #[token("expect")]
    Expect,
    #[token("external")]
    External,
    #[token("final")]
    Final,
    #[token("infix")]
    Infix,
    #[token("inline")]
    Inline,
    #[token("inner")]
    Inner,
    #[token("internal")]
    Internal,
    #[token("lateinit")]
    Lateinit,
    #[token("noinline")]
    Noinline,
    #[token("open")]
    Open,
    #[token("operator")]
    Operator,
    #[token("out")]
    Out,
    #[token("override")]
    Override,
    #[token("private")]
    Private,
    #[token("protected")]
    Protected,
    #[token("public")]
    Public,
    #[token("reified")]
    Reified,
    #[token("sealed")]
    Sealed,
    #[token("suspend")]
    Suspend,
    #[token("tailrec")]
    Tailrec,
    #[token("vararg")]
    Vararg,
    #[token("value")]
    Value,

    // Identifiers
    #[regex(r"[a-zA-Z_][a-zA-Z0-9_]*")]
    #[regex(r"`[^`\r\n]+`")]
    Identifier,

    // Literals
    #[regex(r"[0-9][0-9_]*[uU]?[lL]?")]
    #[regex(r"0[xX][0-9a-fA-F_]+[uU]?[lL]?")]
    #[regex(r"0[bB][01_]+[uU]?[lL]?")]
    IntegerLiteral,

    #[regex(r"([0-9][0-9_]*\.[0-9][0-9_]*([eE][+-]?[0-9]+)?|[0-9][0-9_]*[eE][+-]?[0-9]+)[fF]?")]
    FloatLiteral,

    #[regex(r"'(\\.|[^\\'\r\n])'")]
    CharLiteral,

    StringLiteral,

    MultiLineStringLiteral,

    // String template tokens
    StringStart,
    StringContent,
    StringEnd,
    TemplateExprStart,
    TemplateExprEnd,

    #[token("\"\"\"")]
    TripleQuote,
    #[token("\"")]
    Quote,

    // Punctuation & Operators
    #[token("(")]
    LParen,
    #[token(")")]
    RParen,
    #[token("{")]
    LBrace,
    #[token("}")]
    RBrace,
    #[token("[")]
    LBracket,
    #[token("]")]
    RBracket,
    #[token("<")]
    LAngle,
    #[token(">")]
    RAngle,

    #[token(",")]
    Comma,
    #[token(".")]
    Dot,
    #[token("..")]
    DotDot,
    #[token("..<")]
    DotDotLess,
    #[token(":")]
    Colon,
    #[token("::")]
    ColonColon,
    #[token(";")]
    Semicolon,
    #[token("?")]
    Question,
    #[token("?.")]
    SafeNav,
    #[token("?:")]
    Elvis,
    #[token("!!")]
    BangBang,
    #[token("->")]
    Arrow,
    #[token("=>")]
    DoubleArrow,
    #[token("@")]
    At,

    // Arithmetic & Assignment
    #[token("=")]
    Assign,
    #[token("+")]
    Plus,
    #[token("-")]
    Minus,
    #[token("*")]
    Star,
    #[token("/")]
    Slash,
    #[token("%")]
    Percent,
    #[token("++")]
    PlusPlus,
    #[token("--")]
    MinusMinus,
    #[token("+=")]
    PlusAssign,
    #[token("-=")]
    MinusAssign,
    #[token("*=")]
    StarAssign,
    #[token("/=")]
    SlashAssign,
    #[token("%=")]
    PercentAssign,

    // Logical & Comparison
    #[token("&&")]
    AndAnd,
    #[token("||")]
    OrOr,
    #[token("!")]
    Excl,
    #[token("==")]
    EqEq,
    #[token("!=")]
    ExclEq,
    #[token("===")]
    EqEqEq,
    #[token("!==")]
    ExclEqEq,
    #[token("<=")]
    LessEq,
    #[token(">=")]
    GreaterEq,
}
